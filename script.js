    /* ============ LANGUAGE ============ */
    function setLanguage(lang) {
        const t = translations[lang];
        if (!t) return;

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key] !== undefined) el.textContent = t[key];
        });

        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            if (t[key] !== undefined) el.innerHTML = t[key];
        });

        document.documentElement.lang = lang;
        document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

        document.querySelectorAll('.lang-switch button').forEach(b => {
            b.classList.toggle('active', b.dataset.lang === lang);
        });

        const titles = {
            fr: 'Coopérative Bio - Amlou, Ziiit & Produits Bio à Ouarzazate',
            ar: 'التعاونية  - أملو، زيت و منتجات عضوية في ورزازات',
            en: 'Organic Coop - Amlou, Ziiit & Organic Products in Ouarzazate'
        };
        document.title = titles[lang];

        try { localStorage.setItem('lang', lang); } catch(e) {}
    }

    document.querySelectorAll('.lang-switch button').forEach(btn => {
        btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
    });

    /* ============ DARK MODE ============ */
    function setTheme(mode) {
        if (mode === 'dark') document.body.classList.add('dark');
        else document.body.classList.remove('dark');
        try { localStorage.setItem('theme', mode); } catch(e) {}
    }

    document.getElementById('themeToggle').addEventListener('click', () => {
        const isDark = document.body.classList.contains('dark');
        setTheme(isDark ? 'light' : 'dark');
    });

    /* ============ INIT ============ */
    (function init() {
        let savedTheme;
        try { savedTheme = localStorage.getItem('theme'); } catch(e) {}
        if (!savedTheme) {
            savedTheme = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
        }
        setTheme(savedTheme);

        let savedLang;
        try { savedLang = localStorage.getItem('lang'); } catch(e) {}
        if (!savedLang) {
            const browser = (navigator.language || 'fr').slice(0, 2).toLowerCase();
            savedLang = ['fr', 'ar', 'en'].includes(browser) ? browser : 'fr';
        }
        setLanguage(savedLang);
    })();

    /* ============ HEADER SHADOW ============ */
    const header = document.getElementById('header');
    window.addEventListener('scroll', () => {
        header.classList.toggle('scrolled', window.scrollY > 12);
    }, { passive: true });

    /* ============ MOBILE MENU ============ */
    const burger = document.getElementById('burger');
    const nav = document.getElementById('nav');
    burger.addEventListener('click', () => {
        const isOpen = nav.classList.toggle('open');
        burger.classList.toggle('open', isOpen);
        burger.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    });
    nav.querySelectorAll('a').forEach(link => {
        link.addEventListener('click', () => {
            nav.classList.remove('open');
            burger.classList.remove('open');
            burger.setAttribute('aria-expanded', 'false');
        });
    });

    /* ============ REVEAL ============ */
    const revealEls = document.querySelectorAll('.reveal');
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                const delay = [...entry.target.parentElement.children].indexOf(entry.target) * 90;
                setTimeout(() => entry.target.classList.add('visible'), Math.max(delay, 0));
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.12, rootMargin: '0px 0px -60px 0px' });
    revealEls.forEach(el => observer.observe(el));